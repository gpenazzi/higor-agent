"""Render harness-specific wrappers from the one instruction file.

``agent/higor.md`` is the only copy of the agent's instructions. Every harness wants the
same text under a different filename with different front matter, so generate them rather
than maintaining drifting copies. Regenerate after editing the instructions.

The instructions write the tools as ``higor-agent <command>``. Rendering swaps that for the
full ``uv run`` invocation of this checkout, so the agent can run them from any directory.
"""
from __future__ import annotations

import json
import re
import shlex
from pathlib import Path

from higor_agent import paths

SUMMARY = (
    "Screen new literature for one researcher: sweep Semantic Scholar and arXiv, read "
    "abstracts, score topical relevance and publish a ranked list to their terminal browser. "
    "Use for weekly digests, following up on a paper, or searching a topic."
)

# The checked-in copies under integrations/ use this instead of the real checkout, so
# they read the same on every machine.
REFERENCE_ROOT = Path("/path/to/higor-agent")

# `higor-agent ` at the start of an inline code span or of a line in a code block.
_COMMAND = re.compile(r"(?m)(`|^[ \t]*)higor-agent ")


def project_root() -> Path:
    """The higor-agent checkout, used to build the command."""
    return paths.agent_dir().parent


def command(root: Path | None = None) -> str:
    """The shell command that runs ``higor-agent`` from this checkout, from anywhere."""
    root = root or project_root()
    return f"uv run --quiet --directory {shlex.quote(str(root))} higor-agent"


def instructions(root: Path | None = None) -> str:
    """The instruction file with every ``higor-agent`` command made runnable."""
    text = (paths.agent_dir() / "higor.md").read_text(encoding="utf-8").strip()
    full = command(root)
    return _COMMAND.sub(lambda m: f"{m.group(1)}{full} ", text)


# ── Rendered files ────────────────────────────────────────────────────────────

def claude_skill(root: Path | None = None) -> str:
    """A skill for Claude Code, which Copilot CLI also reads from ``.claude/skills``."""
    return (
        "---\n"
        "name: higor\n"
        f"description: {json.dumps(SUMMARY)}\n"
        f"allowed-tools: {json.dumps(f'Bash({command(root)}:*)')}\n"
        "---\n\n"
        f"{instructions(root)}\n"
    )


def agents_md(root: Path | None = None) -> str:
    """A fragment to paste into AGENTS.md for Codex, Cursor and anything else reading it."""
    return (
        "<!-- Generated by `higor-agent install agents-md`. Edit agent/higor.md instead. -->\n\n"
        f"{instructions(root)}\n"
    )


# ── Writing ───────────────────────────────────────────────────────────────────

def _write(path: Path, text: str, changed: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    changed.append(str(path))


def install(target: str, dest: Path, root: Path | None = None) -> list[str]:
    """Write the wrappers for *target* under *dest*. Returns the paths touched."""
    changed: list[str] = []
    if target == "claude-code":
        _write(dest / ".claude" / "skills" / "higor" / "SKILL.md", claude_skill(root), changed)
    elif target == "agents-md":
        _write(dest / "AGENTS.higor.md", agents_md(root), changed)
    else:
        raise ValueError(f"unknown target {target!r}; expected claude-code or agents-md")
    return changed


def refresh_reference_copies() -> list[str]:
    """Regenerate the checked-in copies under ``integrations/`` for reading in the repo."""
    base = project_root() / "integrations"
    changed: list[str] = []
    _write(
        base / "claude-code" / "skills" / "higor" / "SKILL.md",
        claude_skill(REFERENCE_ROOT),
        changed,
    )
    _write(base / "agents-md" / "AGENTS.higor.md", agents_md(REFERENCE_ROOT), changed)
    return changed
