"""Render harness-specific wrappers from the one instruction file.

``agent/higor.md`` is the only copy of the agent's instructions. Every harness wants the
same text under a different filename with different front matter, so generate them rather
than maintaining three drifting copies. Regenerate after editing the instructions.
"""
from __future__ import annotations

import json
from pathlib import Path

from higor_agent import paths

SUMMARY = (
    "Screen new literature for one researcher: sweep Semantic Scholar and arXiv, read "
    "abstracts, score topical relevance and publish a ranked list to their terminal browser. "
    "Use for weekly digests, following up on a paper, or searching a topic."
)


def project_root() -> Path:
    """The higor-agent checkout, used to build the server command."""
    return paths.agent_dir().parent


def instructions() -> str:
    return (paths.agent_dir() / "higor.md").read_text(encoding="utf-8").strip()


def server_command(root: Path | None = None) -> dict[str, object]:
    """How a host should spawn the stdio server."""
    root = root or project_root()
    return {
        "command": "uv",
        "args": ["run", "--directory", str(root), "higor-agent", "serve"],
    }


# ── Rendered files ────────────────────────────────────────────────────────────

def claude_skill(body: str | None = None) -> str:
    body = body or instructions()
    return (
        "---\n"
        "name: higor\n"
        f"description: {SUMMARY}\n"
        "---\n\n"
        f"{body}\n"
    )


def copilot_chatmode(body: str | None = None) -> str:
    body = body or instructions()
    return (
        "---\n"
        f"description: '{SUMMARY}'\n"
        "tools: ['higor']\n"
        "---\n\n"
        f"{body}\n"
    )


def agents_md(body: str | None = None) -> str:
    """A fragment to paste into AGENTS.md for Codex, Cursor and anything else reading it."""
    body = body or instructions()
    return (
        "<!-- Generated by `higor-agent install agents-md`. Edit agent/higor.md instead. -->\n\n"
        f"{body}\n"
    )


def mcp_config(key: str, root: Path | None = None) -> dict:
    """A host MCP config document. *key* is the top-level key that host expects."""
    return {key: {"higor": {"type": "stdio", **server_command(root)}}}


# ── Writing ───────────────────────────────────────────────────────────────────

def _write(path: Path, text: str, changed: list[str]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    changed.append(str(path))


def _merge_json(path: Path, key: str, changed: list[str], root: Path | None = None) -> None:
    """Add the ``higor`` server to a host config, keeping every other entry intact."""
    doc: dict = {}
    if path.exists():
        try:
            doc = json.loads(path.read_text(encoding="utf-8")) or {}
        except json.JSONDecodeError:
            changed.append(f"{path} (left alone: not valid JSON, add the server by hand)")
            return
    servers = doc.setdefault(key, {})
    if not isinstance(servers, dict):
        changed.append(f"{path} (left alone: '{key}' is not an object)")
        return
    servers["higor"] = {"type": "stdio", **server_command(root)}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(doc, indent=2) + "\n", encoding="utf-8")
    changed.append(str(path))


def install(target: str, dest: Path, root: Path | None = None) -> list[str]:
    """Write the wrappers for *target* under *dest*. Returns the paths touched."""
    changed: list[str] = []
    if target == "claude-code":
        _write(dest / ".claude" / "skills" / "higor" / "SKILL.md", claude_skill(), changed)
        _merge_json(dest / ".mcp.json", "mcpServers", changed, root)
    elif target == "copilot":
        _write(dest / ".github" / "chatmodes" / "higor.chatmode.md", copilot_chatmode(), changed)
        _merge_json(dest / ".vscode" / "mcp.json", "servers", changed, root)
    elif target == "agents-md":
        _write(dest / "AGENTS.higor.md", agents_md(), changed)
        _merge_json(dest / ".mcp.json", "mcpServers", changed, root)
    else:
        raise ValueError(
            f"unknown target {target!r}; expected claude-code, copilot or agents-md"
        )
    return changed


def refresh_reference_copies(root: Path | None = None) -> list[str]:
    """Regenerate the checked-in copies under ``integrations/`` for reading in the repo."""
    root = root or project_root()
    base = root / "integrations"
    changed: list[str] = []
    _write(base / "claude-code" / "skills" / "higor" / "SKILL.md", claude_skill(), changed)
    _write(
        base / "claude-code" / ".mcp.json",
        json.dumps(mcp_config("mcpServers", root), indent=2) + "\n",
        changed,
    )
    _write(base / "copilot" / "higor.chatmode.md", copilot_chatmode(), changed)
    _write(
        base / "copilot" / "mcp.json",
        json.dumps(mcp_config("servers", root), indent=2) + "\n",
        changed,
    )
    _write(base / "agents-md" / "AGENTS.higor.md", agents_md(), changed)
    return changed
